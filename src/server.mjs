import http from 'node:http';
import path from 'node:path';
import { fileURLToPath,pathToFileURL } from 'node:url';
import { readFile } from 'node:fs/promises';
import { createHash,timingSafeEqual } from 'node:crypto';
import { TaskStore } from './store.mjs';
import { Engine } from './engine.mjs';
import { validateCreate } from './validation.mjs';
import { BridgeError } from './errors.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const digest=x=>createHash('sha256').update(x).digest();
const routeId='([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})';
const privateHeaders={
  'Cache-Control':'no-store','X-Content-Type-Options':'nosniff','Referrer-Policy':'no-referrer',
  'Content-Security-Policy':"default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'"
};
async function readJson(req) {
  if(!/^application\/json(?:\s*;|$)/i.test(req.headers['content-type']||'')) throw new BridgeError(415,'JSON_REQUIRED','请以 application/json 发送请求。');
  let size=0;const chunks=[];
  for await(const chunk of req){size+=chunk.length;if(size>16384) throw new BridgeError(413,'BODY_TOO_LARGE','请求资料过大。');chunks.push(chunk);}
  try{return JSON.parse(Buffer.concat(chunks).toString('utf8'));}catch{throw new BridgeError(400,'INVALID_JSON','无法解析请求资料。');}
}
export async function createBridge({token,dataDir=path.join(root,'.data'),allowLive=false,publicOrigin='',driverFactory,profilePath=path.join(root,'config/cityline.local.json'),playwrightModulePath}={}) {
  if(typeof token!=='string'||token.length<43||/\s/.test(token)||token.startsWith('replace-')) throw new Error('Configure a random bridge token generated by npm run init.');
  let origin='';
  if(publicOrigin){const u=new URL(publicOrigin);if(u.protocol!=='https:'||u.username||u.password||u.pathname!=='/'||u.search||u.hash) throw new Error('Public origin must be an HTTPS origin.');origin=u.origin;}
  const store=await new TaskStore(dataDir).init();
  const factory=driverFactory||(async task=>{
    const {createDriver}=await import('./browser.mjs');
    return createDriver({mode:task.mode,profilePath,dataDir,playwrightModulePath});
  });
  const engine=new Engine({store,driverFactory:factory,allowLive});
  const authHash=digest(token);
  const limits=new Map();
  const server=http.createServer({maxHeaderSize:8192},async(req,res)=>{
    const send=(status,value)=>{if(!res.headersSent){res.writeHead(status,{...privateHeaders,'Content-Type':'application/json; charset=utf-8'});res.end(JSON.stringify(value));}};
    try {
      const host=req.headers.host||'';
      const localPort=server.address()?.port;
      const allowedHosts=new Set(['127.0.0.1:'+localPort,'localhost:'+localPort,...(origin?[new URL(origin).host]:[])]);
      if(!allowedHosts.has(host)) throw new BridgeError(403,'HOST_REJECTED','请求来源主机未配置。');
      if(req.headers.origin&&!new Set(['http://127.0.0.1:'+localPort,'http://localhost:'+localPort,...(origin?[origin]:[])]).has(req.headers.origin)) throw new BridgeError(403,'ORIGIN_REJECTED','不接受该网页来源的请求。');
      const url=new URL(req.url,'http://'+host);
      if(url.search) throw new BridgeError(400,'QUERY_REJECTED','接口不接受网址中的资料或密钥。');
      if(req.method==='GET'&&url.pathname==='/health') return send(200,{ok:true,version:'0.1.0'});
      const staticFiles={'/':['index.html','text/html; charset=utf-8'],'/app.mjs':['app.mjs','text/javascript; charset=utf-8'],'/style.css':['style.css','text/css; charset=utf-8']};
      if(req.method==='GET'&&Object.hasOwn(staticFiles,url.pathname)) {
        const [file,type]=staticFiles[url.pathname];const content=await readFile(path.join(root,'public',file));
        res.writeHead(200,{...privateHeaders,'Content-Type':type});res.end(content);return;
      }
      if(!url.pathname.startsWith('/v1/')) throw new BridgeError(404,'NOT_FOUND','接口不存在。');
      const header=req.headers.authorization||'';
      if(typeof header!=='string'||!header.startsWith('Bearer ')||!timingSafeEqual(digest(header.slice(7)),authHash)) throw new BridgeError(401,'UNAUTHORIZED','服务认证失败。');
      const ip=req.socket.remoteAddress||'local';const now=Date.now();
      if(limits.size>1000) for(const [k,v] of limits) if(now-v.since>60000) limits.delete(k);
      const rate=limits.get(ip);if(!rate||now-rate.since>60000) limits.set(ip,{since:now,count:1});else if(++rate.count>120) throw new BridgeError(429,'RATE_LIMITED','请求过于频繁，请稍后再试。');
      if(req.method==='POST'&&url.pathname==='/v1/tasks') return send(201,await engine.create(validateCreate(await readJson(req))));
      const match=url.pathname.match(new RegExp('^/v1/tasks/'+routeId+'(?:/(start|resume))?$','i'));
      if(!match) throw new BridgeError(404,'NOT_FOUND','接口不存在。');
      const [,id,action]=match;
      if(req.method==='GET'&&!action) return send(200,engine.get(id));
      if(req.method==='POST'&&action==='start') {const body=await readJson(req);if(!body||typeof body!=='object'||Array.isArray(body)||Object.keys(body).length) throw new BridgeError(400,'INVALID_INPUT','开始任务请求应为空对象。');return send(202,await engine.start(id));}
      if(req.method==='POST'&&action==='resume') return send(202,await engine.resume(id,await readJson(req)));
      throw new BridgeError(405,'METHOD_REJECTED','该接口不支持此操作。');
    } catch(error) {
      if(error instanceof BridgeError) send(error.status,{error:{code:error.code,message:error.message}});
      else send(500,{error:{code:'INTERNAL_ERROR',message:'本机服务处理失败，请检查配置；请求资料不会写入日志。'}});
    }
  });
  server.requestTimeout=20000;server.headersTimeout=15000;server.keepAliveTimeout=5000;
  server.on('clientError',(_err,socket)=>{socket.end('HTTP/1.1 400 Bad Request\r\nConnection: close\r\n\r\n');});
  return {server,engine,store,listen:(port=8787)=>new Promise((resolve,reject)=>{server.once('error',reject);server.listen(port,'127.0.0.1',()=>{server.removeListener('error',reject);resolve(server.address());});}),close:async()=>{await new Promise(r=>server.close(()=>r()));try{await engine.close();}finally{await store.close();}}};
}

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href) {
  let bridge;
  try {
    bridge=await createBridge({token:process.env.CITYLINE_BRIDGE_TOKEN,dataDir:path.resolve(process.env.CITYLINE_DATA_DIR||path.join(root,'.data')),allowLive:process.env.CITYLINE_ALLOW_LIVE==='true',publicOrigin:process.env.CITYLINE_PUBLIC_ORIGIN||'',profilePath:path.resolve(process.env.CITYLINE_PROFILE_PATH||path.join(root,'config/cityline.local.json')),playwrightModulePath:process.env.PLAYWRIGHT_MODULE_PATH});
    const port=Number(process.env.CITYLINE_PORT||8787);if(!Number.isInteger(port)||port<1||port>65535) throw new Error('Invalid local port.');
    const address=await bridge.listen(port);
    console.log('Cityline GPT Bridge ready: http://127.0.0.1:'+address.port+' (local only)');
    const stop=async()=>{await bridge.close();process.exit(0);};process.once('SIGINT',stop);process.once('SIGTERM',stop);
  } catch {console.error('Bridge could not start. Run npm run init and check the local configuration. No request data was logged.');process.exitCode=1;if(bridge)await bridge.close();}
}
